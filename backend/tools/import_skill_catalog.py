"""Explicit, repeatable catalog import (run from the backend directory).

  python -m tools.import_skill_catalog catalog.json --initialize
  python -m tools.import_skill_catalog custom.csv --embed
  python -m tools.import_skill_catalog --prewarm

Set SKILL_CATALOG_DATABASE_URL; the dimension defaults to 384 and is configured
with SKILL_CATALOG_EMBEDDING_DIMENSIONS. JSON accepts a list or {"concepts": [...]}.
CSV uses concept field names as headers, with arrays serialized as JSON or pipe
separated text. Embeddings must be JSON number arrays, generated by the same
model as runtime queries. Absent embeddings remain available to lexical search.
Repeated imports upsert concept_id. --replace explicitly removes the old catalog.
ESCO exports require mapping their URI/preferredLabel fields to concept_id/label;
this importer deliberately never guesses semantic column mappings.
"""

from __future__ import annotations

import argparse
import asyncio
import csv
from dataclasses import replace
import json
from pathlib import Path
from typing import Any

from app.services.skill_catalog_store import SkillCatalogStore, SkillConcept
from app.services.skill_embeddings import embed_passages


def load_concepts(path: Path) -> list[SkillConcept]:
    if path.suffix.casefold() == '.csv':
        with path.open(encoding='utf-8-sig', newline='') as handle:
            rows: Any = list(csv.DictReader(handle))
        for row in rows:
            for field in ('aliases', 'positive_signals', 'negative_signals'):
                raw = row.get(field, '').strip()
                row[field] = json.loads(raw) if raw.startswith('[') else [v.strip() for v in raw.split('|') if v.strip()]
            raw_embedding = row.get('embedding', '').strip()
            row['embedding'] = json.loads(raw_embedding) if raw_embedding else None
            for field in ('version', 'source'):
                if not row.get(field):
                    row.pop(field, None)
    else:
        with path.open(encoding='utf-8-sig') as handle:
            rows = json.load(handle)
        if isinstance(rows, dict):
            rows = rows.get('concepts')
    if not isinstance(rows, list) or any(not isinstance(row, dict) for row in rows):
        raise ValueError('catalog must contain a list of concept objects')
    return [SkillConcept.from_mapping(row) for row in rows]


async def _embed_concepts(concepts: list[SkillConcept]) -> list[SkillConcept]:
    passages = ['\n'.join((c.label, 'Aliases: ' + ', '.join(c.aliases), c.definition,
                           'Positive signals: ' + '; '.join(c.positive_signals),
                           'Negative signals: ' + '; '.join(c.negative_signals), c.domain))
                for c in concepts]
    vectors = await embed_passages(passages, allow_download=True)
    if len(vectors) != len(concepts):
        raise ValueError('embedding provider returned an unexpected vector count')
    return [replace(concept, embedding=tuple(vector)) for concept, vector in zip(concepts, vectors)]


async def _run(args: argparse.Namespace) -> int:
    if args.prewarm and not args.embed:
        await embed_passages(['Catalog model prewarm'], allow_download=True)
    if args.path is None:
        return 0
    concepts = await asyncio.to_thread(load_concepts, args.path)
    store = SkillCatalogStore.from_env()
    if not store.configured:
        raise ValueError('SKILL_CATALOG_DATABASE_URL is required for a persistent import')
    try:
        if args.embed:
            concepts = await _embed_concepts(concepts)
        if args.initialize:
            await store.initialize()
        return await store.import_concepts(concepts, replace=args.replace)
    finally:
        await store.close()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('path', type=Path, nargs='?')
    parser.add_argument('--initialize', action='store_true', help='Create extension/table using an administrative DB role')
    parser.add_argument('--replace', action='store_true', help='Atomically replace the entire existing catalog')
    parser.add_argument('--embed', action='store_true', help='Download/prewarm the local model and explicitly regenerate all imported embeddings')
    parser.add_argument('--prewarm', action='store_true', help='Download/cache the local model, optionally without a catalog or database')
    args = parser.parse_args()
    if args.path is None and (not args.prewarm or args.embed or args.initialize or args.replace):
        parser.error('a catalog path is required except for standalone --prewarm')
    try:
        count = asyncio.run(_run(args))
    except Exception as exc:
        # Avoid echoing credentials or connection strings from driver exceptions.
        parser.exit(1, f'Catalog import failed ({type(exc).__name__}); check input and database configuration.\n')
    print(f'Imported {count} skill concepts.' if args.path is not None else 'Embedding model prewarmed.')


if __name__ == '__main__':
    main()
